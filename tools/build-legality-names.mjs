#!/usr/bin/env node
/**
 * Write `scripts/data/legality-names.mjs` — the Legality Code by item type and exact name · SR3 p.273.
 *
 *   node tools/build-legality-names.mjs           write the file
 *   node tools/build-legality-names.mjs --check   exit 1 if it is stale — changes nothing
 *
 * Derived from `legality-table.mjs` and the pack documents in `packs-src/`; `tests/legality.test.mjs` runs the check,
 * so editing the table or renaming a document without re-running this fails the suite.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { readSourceDir } from './lib/pack-source.mjs';
import { nameTable } from './lib/legality-fill.mjs';
import { LEGALITY } from '../scripts/data/legality-table.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'scripts', 'data', 'legality-names.mjs');

export function render() {
  const docs = {};
  for (const pack of Object.keys(LEGALITY)) docs[pack] = readSourceDir(join(ROOT, 'packs-src', pack));
  const names = nameTable(docs);
  const body = Object.entries(names).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
  return `/**
 * Legality Codes by item type and exact name · SR3 p.273 (2026-10-26). GENERATED by \`tools/build-legality-names.mjs\` — do not edit.
 *
 * For an owned copy with no usable \`_stats.compendiumSource\`: the hand-kept packs' ids (\`sr3e-firearm-0072\`) are not
 * valid Foundry document ids, so a dropped item's source comes out null and \`legality-table.mjs\` cannot find it.
 * A name two documents share with different codes is left out — name matching never guesses.
 */
export const LEGALITY_BY_NAME = {
${body}
};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = render();
  if (process.argv.includes('--check')) {
    let now = '';
    try { now = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (now !== next) { console.log('legality-names.mjs is stale — run: node tools/build-legality-names.mjs'); process.exit(1); }
    console.log('legality-names.mjs is current');
  } else {
    writeFileSync(OUT, next, 'utf8');
    console.log(`wrote ${OUT}`);
  }
}
