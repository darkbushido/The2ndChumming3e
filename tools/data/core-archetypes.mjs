/**
 * The 16 Sample Characters of the SR3 core rulebook — stats only, as the book prints them.
 *
 * Source: *Shadowrun, Third Edition* (FASA/FanPro, FAN25000) — the character page of each archetype
 * (pp.65-80) and its record sheet (pp.326-329, "Sample Character Record Sheets"). ⚠ The PDF is the
 * authority (PDF page = printed + 2). Only stats are entered: no flavour text, quotes or descriptions.
 *
 * ⚠ **Attributes are the book's FIRST number — the natural, unaugmented rating.** The parenthesised
 * figure is the augmented one; the system reaches it itself from the cyberware/adept items below
 * (and a troll's dermal armour), exactly as `SR3EActor._prepareCharacter` does. Entering the
 * augmented figure as the base would count the chrome twice.
 * ⚠ **The race is the book's race, never pre-converted** (SR3 p.56 racial modifiers are a rule on
 * top, applied by whoever plays the archetype as another race).
 *
 * Item DSL (`tools/build-core-archetypes.mjs` resolves each against the shipped packs):
 *   cy  cyberware      { n, r:rating, g:'Alpha', q:count, d:note }
 *   bw  bioware        sp  spell { n, f:Force, x:'Exclusive'|'Fetish' }       ap  adept power
 *   fw  firearm        { n, rounds:total carried, type:ammo type, extra:[{n,type}], sl:smartlinked, acc:'…' }
 *   ml  melee / pr  projectile / th  thrown / ar  armor / am  ammunition / ge  gear { n, q }
 */

// ── helpers ──────────────────────────────────────────────────────────────────────────────
const act = (name, rating, spec = '') => ({ tier: 'active', name, rating, spec });
const knw = (name, rating, spec = '') => ({ tier: 'knowledge', name, rating, spec });
const lan = (name, rating, rw, spec = '') => ({ tier: 'language', name, rating, rw, spec });

const cy = (n, o = {}) => ({ t: 'cy', n, ...o });
/** A mod that sits inside cyberears/cybereyes' free .5 Essence (SR3 p.62 worked example) — a real item, but it costs no Essence of its own. */
const inn = (n, o = {}) => cy(n, { ...o, free: true });
const al = (n, o = {}) => cy(n, { g: 'Alpha', ...o });
const bw = (n, o = {}) => ({ t: 'bw', n, ...o });
const sp = (n, f, x = '') => ({ t: 'sp', n, f, x });
const ap = (n, o = {}) => ({ t: 'ap', n, ...o });
const fw = (n, o = {}) => ({ t: 'fw', n, ...o });
const ml = (n, o = {}) => ({ t: 'ml', n, ...o });
const pr = (n, o = {}) => ({ t: 'pr', n, ...o });
const th = (n, o = {}) => ({ t: 'th', n, ...o });
const ar = (n, o = {}) => ({ t: 'ar', n, ...o });
const am = (n, o = {}) => ({ t: 'am', n, ...o });
const ge = (n, o = {}) => ({ t: 'ge', n, ...o });

